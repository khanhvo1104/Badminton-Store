/// Canonical date/time format patterns for UI and logging.
abstract final class DateFormats {
  static const String displayDate = 'dd/MM/yyyy';
  static const String displayDateTime = 'dd/MM/yyyy HH:mm';
  static const String displayTime = 'HH:mm';
  static const String isoDate = 'yyyy-MM-dd';
  static const String isoDateTime = "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'";
  static const String orderReference = 'yyyyMMdd';
}
